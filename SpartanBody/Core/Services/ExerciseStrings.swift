/// Localize an exercise-library content string (falls back to English).
func EXL(_ english: String) -> String { ExerciseStrings.value(english) }

/// Localizes a plan line like `"Bench Press 4×8"` or `"Plank 3×60 sec"`.
///
/// The coach stores these as an English exercise name followed by a
/// sets×reps suffix. We translate only the name and keep the numeric suffix
/// intact, so "Dead Hang 4×30 sec" becomes "Colgado en barra 4×30 sec".
func EXLPlanLine(_ line: String) -> String {
    // Find where the "4×8" / "3x60 sec" part starts.
    guard let r = line.range(of: #"\s+\d+\s*[×x]\s*\d+"#, options: .regularExpression) else {
        return EXL(line)   // no suffix — translate the whole thing
    }
    let name = String(line[line.startIndex..<r.lowerBound])
    let suffix = String(line[r.lowerBound...])
    return EXL(name) + suffix
}

/// Localizes a library rep target like `"10 each leg"` or `"30-60 sec"`;
/// the numbers stay as they are.
func EXLReps(_ reps: String) -> String {
    func L(_ k: String) -> String { NSLocalizedString(k, comment: "") }
    return reps
        .replacingOccurrences(of: " each leg", with: " " + L("reps.eachLeg"))
        .replacingOccurrences(of: " each", with: " " + L("reps.eachSide"))
        .replacingOccurrences(of: " total", with: " " + L("reps.total"))
        .replacingOccurrences(of: " sec", with: " s")
}
